// Builds the ISOLATED Apps Script test package for Crew Intelligence V2.3 (docs/CREW-GAS-TEST-SETUP.md):
// two bundles the owner pastes by hand into two NEW Apps Script projects, plus their manifests.
//
//   node scripts/gas-test/build-test-package.mjs <outDir>
//
//   <outDir>/api/FcTestApi.gs         production sources embedded UNCHANGED + the guard, fixture and smoke runner
//   <outDir>/api/appsscript.json      scopes: calendar.readonly, userinfo.email (no write scope, no network scope)
//   <outDir>/seeder/FcTestSeeder.gs   guard + fixture + seeder only (no production source is needed)
//   <outDir>/seeder/appsscript.json   scope: calendar (read/write), no web app
//   <outDir>/MANIFEST.txt             sha256 of every included source file and every output file
//
// The output directory must be OUTSIDE the repository (the bundles hold a fixture and are not for Git) and
// empty or absent. This script only writes files: it never deploys, never touches the network and reads no
// property, calendar or credential.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, realpathSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve, relative, isAbsolute, basename, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../../', import.meta.url));
const PRODUCTION_DIR = join(REPO, 'backend', 'apps-script');
const TEST_DIR = join(REPO, 'backend', 'apps-script-test');

/** Production sources, in bundle order (each embedded byte-identical). */
export const PRODUCTION_FILES = Object.freeze([
  'CondorAdapterV2.gs', 'RosterModelV2.gs', 'AirportsV2.gs', 'CondorCodesV2.gs', 'RosterApiV2.gs', 'RouterV2.gs',
  'DeparturesV2.gs', 'FlightInfoV2.gs', 'CrewCoreV2.gs', 'CrewCondorV2.gs', 'CrewApiV2.gs',
]);
export const API_TEST_FILES = Object.freeze(['TestGuardV2.gs', 'TestFixturesV2.gs', 'TestSmokeV2.gs']);
export const SEEDER_TEST_FILES = Object.freeze(['TestGuardV2.gs', 'TestFixturesV2.gs', 'TestSeederV2.gs']);
export const API_SCOPES = Object.freeze(['https://www.googleapis.com/auth/calendar.readonly', 'https://www.googleapis.com/auth/userinfo.email']);
export const SEEDER_SCOPES = Object.freeze(['https://www.googleapis.com/auth/calendar']);

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
export const KIND_PRODUCTION = 'production source (unmodified)';
export const KIND_TEST = 'test-only source';

/** Banner delimiters; tests locate an embedded file between them. */
export const beginBanner = (kind, name, digest) => `// ---- BEGIN ${kind}: ${name} (sha256 ${digest}) ----`;
export const endBanner = (kind, name) => `// ---- END ${kind}: ${name} ----`;

function readSource(dir, name) {
  const text = readFileSync(join(dir, name), 'utf8');
  if (text.includes('\r')) throw new Error(`${name}: CR characters are not allowed (embedding must stay byte-identical)`);
  return text;
}

/** One embedded file: BEGIN banner, the exact file text (a newline is added only if it lacks one), END banner. */
function embed(kind, dir, name) {
  const text = readSource(dir, name);
  const body = text.endsWith('\n') ? text : `${text}\n`;
  return { text: `${beginBanner(kind, name, sha256(Buffer.from(text, 'utf8')))}\n${body}${endBanner(kind, name)}\n`, digest: sha256(Buffer.from(text, 'utf8')) };
}

const HEADER = (title, scopes, note) => `// ============================================================================
// ${title}
// SYNTHETIC TEST BUNDLE. NEVER paste this into the production Apps Script project.
// Generated by scripts/gas-test/build-test-package.mjs; do not edit by hand (rebuild instead).
// Manifest scopes: ${scopes.join(', ')}
// ${note}
// ============================================================================

`;

function manifestJson(file) {
  const parsed = JSON.parse(readFileSync(join(TEST_DIR, file), 'utf8'));
  return `${JSON.stringify(parsed, null, 2)}\n`;
}

function bundle(title, scopes, note, productionFiles, testFiles) {
  const parts = [];
  const sources = [];
  for (const name of productionFiles) {
    const e = embed(KIND_PRODUCTION, PRODUCTION_DIR, name);
    parts.push(e.text);
    sources.push({ path: `backend/apps-script/${name}`, digest: e.digest });
  }
  for (const name of testFiles) {
    const e = embed(KIND_TEST, TEST_DIR, name);
    parts.push(e.text);
    sources.push({ path: `backend/apps-script-test/${name}`, digest: e.digest });
  }
  return { source: HEADER(title, scopes, note) + parts.join('\n'), sources };
}

/** The API project: production files unchanged, then the test-only guard, fixture and smoke runner. */
export function buildApi() {
  const b = bundle('FC-TEST Crew API (project 1 of 2)', API_SCOPES,
    'No write scope and no external-request scope: this project cannot write a calendar or reach the network.',
    PRODUCTION_FILES, API_TEST_FILES);
  return { name: 'FcTestApi.gs', source: b.source, manifest: manifestJson('appsscript.api.json'), sources: b.sources };
}

/** The seeder project: guard + fixture + seeder only (the fixture needs no production source). */
export function buildSeeder() {
  const b = bundle('FC-TEST Seeder (project 2 of 2)', SEEDER_SCOPES,
    'The only project with a write scope; it can touch only calendars that pass the guard. Delete it after use.',
    [], SEEDER_TEST_FILES);
  return { name: 'FcTestSeeder.gs', source: b.source, manifest: manifestJson('appsscript.seeder.json'), sources: b.sources };
}

/** MANIFEST.txt text: deterministic (no timestamps). */
export function manifestText(api, seeder) {
  const lines = ['FC-TEST package manifest (synthetic test package; never paste into the production Apps Script project)',
    'generated by scripts/gas-test/build-test-package.mjs', '', '[api bundle sources, in order]'];
  for (const s of api.sources) lines.push(`${s.digest}  ${s.path}`);
  lines.push('', '[seeder bundle sources, in order]');
  for (const s of seeder.sources) lines.push(`${s.digest}  ${s.path}`);
  lines.push('', '[output files]');
  lines.push(`${sha256(Buffer.from(api.source))}  api/${api.name}`);
  lines.push(`${sha256(Buffer.from(api.manifest))}  api/appsscript.json`);
  lines.push(`${sha256(Buffer.from(seeder.source))}  seeder/${seeder.name}`);
  lines.push(`${sha256(Buffer.from(seeder.manifest))}  seeder/appsscript.json`);
  return `${lines.join('\n')}\n`;
}

const outside = (parent, child) => { const rel = relative(parent, child); return rel.startsWith(`..${sep}`) || rel === '..' || isAbsolute(rel); };

/** Resolves the output directory through existing ancestors (symlink-safe) and refuses a place inside the repository. */
export function checkedOutDir(outDir) {
  if (!outDir) throw new Error('Usage: node scripts/gas-test/build-test-package.mjs <outDir>  (outside the repository)');
  const out = resolve(outDir);
  let ancestor = out;
  const suffix = [];
  while (!existsSync(ancestor)) { suffix.unshift(basename(ancestor)); ancestor = dirname(ancestor); }
  const destination = resolve(realpathSync(ancestor), ...suffix);
  if (!outside(realpathSync(REPO), destination)) throw new Error('The output directory must be outside the repository');
  if (existsSync(out) && readdirSync(out).length) throw new Error('The output directory must be empty or absent');
  return out;
}

/** Writes the package; returns the output directory and the hashes. Never deploys. */
export function writePackage(outDir) {
  const out = checkedOutDir(outDir);
  const api = buildApi();
  const seeder = buildSeeder();
  mkdirSync(join(out, 'api'), { recursive: true });
  mkdirSync(join(out, 'seeder'), { recursive: true });
  writeFileSync(join(out, 'api', api.name), api.source, { flag: 'wx' });
  writeFileSync(join(out, 'api', 'appsscript.json'), api.manifest, { flag: 'wx' });
  writeFileSync(join(out, 'seeder', seeder.name), seeder.source, { flag: 'wx' });
  writeFileSync(join(out, 'seeder', 'appsscript.json'), seeder.manifest, { flag: 'wx' });
  writeFileSync(join(out, 'MANIFEST.txt'), manifestText(api, seeder), { flag: 'wx' });
  return { out, api, seeder };
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  try {
    const { out } = writePackage(process.argv[2]);
    console.log(`FC-TEST package written to ${out} (api/, seeder/, MANIFEST.txt). Not deployed; nothing contacted.`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
