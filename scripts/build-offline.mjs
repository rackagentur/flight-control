// Explicit generated precache: only app entry files, src/*.js, and shipped assets.
// Run after frontend edits; --check fails if the checked-in worker is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const digest = (value) => createHash('sha256').update(value).digest('hex');
function files(dir) {
  return readdirSync(join(root, dir), { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]);
}
const paths = ['index.html', 'manifest.webmanifest', ...files('src').filter((p) => p.endsWith('.js')),
  ...files('assets').filter((p) => /\.(css|svg|png)$/.test(p))].sort();
const assets = paths.map((path) => ({ path: path.replaceAll('\\', '/'), sha256: digest(readFileSync(join(root, path))) }));
const body = readFileSync(join(root, 'scripts/service-worker.js'), 'utf8');
const version = digest(JSON.stringify(assets) + body).slice(0, 20);
const result = `// Generated by scripts/build-offline.mjs. Static assets only.\nconst VERSION = '${version}';\nconst ASSETS = ${JSON.stringify(assets, null, 2)};\n\n${body}`;
if (process.argv.includes('--check')) {
  if (readFileSync(join(root, 'sw.js'), 'utf8') !== result) throw new Error('Offline worker is stale. Run npm run build:offline.');
} else writeFileSync(join(root, 'sw.js'), result);
console.log(`Offline shell: ${assets.length} files, version ${version}`);
