// Generates backend/apps-script/CondorCodesV2.gs from src/airlines/condor/roster-codes.js, so the
// backend classifier and the Condor airline pack share ONE roster-code table.
// Run: node scripts/gen-condor-codes-gs.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CONDOR_ROSTER_CODES, CONDOR_FLIGHT_DESIGNATORS } from '../src/airlines/condor/roster-codes.js';

const KEY_ORDER = ['id', 'match', 'kind', 'subtype', 'protected', 'source'];

/** JSON-safe literal for a frozen value; object keys in a stable order. */
function literal(v) {
  if (Array.isArray(v)) return `Object.freeze([${v.map(literal).join(', ')}])`;
  if (v && typeof v === 'object') {
    const keys = Object.keys(v).sort((a, b) => (KEY_ORDER.indexOf(a) + 1 || 99) - (KEY_ORDER.indexOf(b) + 1 || 99) || (a < b ? -1 : 1));
    return `Object.freeze({ ${keys.map((k) => `${k}: ${literal(v[k])}`).join(', ')} })`;
  }
  return JSON.stringify(v);
}

export function renderCondorCodesGs() {
  return [
    '// GENERATED by scripts/gen-condor-codes-gs.mjs from src/airlines/condor/roster-codes.js. Do not edit by hand.',
    '// Condor roster codes: raw feed title → canonical Flight Control concept (contract v2), in match',
    '// order (first match wins). `exact` compares the cleaned title; `pattern` is an anchored regex',
    '// source. Read by fcv2ClassifyEvent_ at call time only (this file loads after CondorAdapterV2.gs).',
    `const FCV2_CONDOR_CODES_ = Object.freeze({`,
    `  flightDesignators: ${literal(CONDOR_FLIGHT_DESIGNATORS)},`,
    '  codes: Object.freeze([',
    ...CONDOR_ROSTER_CODES.map((c) => `    ${literal(c)},`),
    '  ]),',
    '});',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../backend/apps-script/CondorCodesV2.gs', import.meta.url), renderCondorCodesGs());
  console.log(`CondorCodesV2.gs: ${CONDOR_ROSTER_CODES.length} codes, ${CONDOR_FLIGHT_DESIGNATORS.length} designator(s)`);
}
